// Run after npm run build. Optional arguments: Playwright package and Chromium executable.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const http = require('node:http')
const { chromium } = require(process.argv[2] || 'playwright')

async function main() {
  const dist = path.resolve(__dirname, '../dist')
  const server = http.createServer((request, response) => {
    const pathname = decodeURIComponent(new URL(request.url, 'http://localhost').pathname)
    const file = path.resolve(dist, '.' + (pathname === '/' ? '/index.html' : pathname))
    if (!file.startsWith(dist + path.sep) || !fs.existsSync(file)) { response.writeHead(404).end(); return }
    response.setHeader('Content-Type', ({ '.js': 'text/javascript', '.css': 'text/css', '.html': 'text/html' })[path.extname(file)] || 'application/octet-stream')
    response.end(fs.readFileSync(file))
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  let browser
  let page
  try {
    browser = await chromium.launch({ headless: true, executablePath: process.argv[3] })
    page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(() => {
      if (localStorage.getItem('blocks-test-seeded')) return
      const note = { id: 'blocks-test', title: 'Blocos de validação', content: 'Texto antes dos blocos.\n\n```javascript\nconst count = 1;\nconsole.log(count);\n```\n\n> [!TIP] Uma dica\n> Primeira linha\n> Segunda linha\n\nTexto depois dos blocos.', folder: 'Testes', tags: [], createdAt: Date.now(), updatedAt: Date.now() }
      localStorage.setItem('pyrite_vault_notes', JSON.stringify([note]))
      localStorage.setItem('pyrite_vault_folders', JSON.stringify(['Testes']))
      localStorage.setItem('blocks-test-seeded', '1')
    })
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    const openNote = () => page.locator('[title="Blocos de validação"]').click()
    const surface = page.locator('.pyrita-editor-surface')
    const code = page.locator('.editor-code-block').first()
    const callout = page.locator('.editor-callout').first()
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('pyrite_vault_notes')).find(note => note.id === 'blocks-test').content)
    await openNote()
    await code.getByLabel('Conteúdo do bloco de código').waitFor()
    assert.equal(await code.getByLabel('Conteúdo do bloco de código').inputValue(), 'const count = 1;\nconsole.log(count);')
    assert.equal(await callout.getByLabel('Título do callout').inputValue(), 'Uma dica')
    assert.equal(await callout.getByLabel('Conteúdo do callout').inputValue(), 'Primeira linha\nSegunda linha')
    const content = '<script>texto literal</script>\nconst value = "a|b";\n```\n\treturn value;'
    await code.getByLabel('Título do bloco de código').fill('Exemplo "API"')
    await code.getByLabel('Linguagem do código').fill('typescript')
    await code.getByLabel('Conteúdo do bloco de código').fill('')
    await code.getByLabel('Conteúdo do bloco de código').focus()
    await page.keyboard.insertText(content)
    assert.equal(await code.getByLabel('Conteúdo do bloco de código').inputValue(), content)
    await callout.getByLabel('Conteúdo do callout').fill('Dica editada\nCom segunda linha')
    await code.getByRole('button', { name: 'Escrever abaixo' }).click()
    await page.keyboard.insertText('Texto entre código e dica.')
    const paragraphAfterCallout = page.locator('.callout-wrapper').first().locator('xpath=following-sibling::p[1]')
    await paragraphAfterCallout.click()
    await page.keyboard.insertText('Linha abaixo do callout.')
    // Leaving the main surface flushes paragraph edits before a note switch/reload.
    await code.getByLabel('Título do bloco de código').focus()
    assert.match(await saved(), /Texto entre código e dica\./)
    assert.match(await saved(), /Linha abaixo do callout\./)
    await page.reload(); await openNote()
    assert.equal(await code.getByLabel('Título do bloco de código').inputValue(), 'Exemplo "API"')
    assert.equal(await code.getByLabel('Linguagem do código').inputValue(), 'typescript')
    assert.equal(await code.getByLabel('Conteúdo do bloco de código').inputValue(), content)
    assert.equal(await callout.getByLabel('Conteúdo do callout').inputValue(), 'Dica editada\nCom segunda linha')
    await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.copiedCode = text } } }) })
    await code.getByRole('button', { name: 'Copiar código' }).click()
    assert.equal(await page.evaluate(() => window.copiedCode), content)
    await callout.getByRole('button', { name: 'Excluir callout' }).click()
    assert.equal(await page.locator('.editor-callout').count(), 0)
    assert.doesNotMatch(await saved(), /> \[!TIP\]/)
    assert.match(await saved(), /Texto antes dos blocos/)
    assert.match(await saved(), /Texto depois dos blocos/)
    // A click on padding beneath the content becomes a real text line.
    await surface.evaluate(element => element.scrollIntoView({ block: 'end' }))
    const bounds = await surface.boundingBox()
    const outer = await surface.locator('..').boundingBox()
    await page.mouse.click(bounds.x + 80, Math.min(bounds.y + bounds.height + 42, outer.y + outer.height - 15))
    await page.keyboard.insertText('Linha criada em espaço vazio.')
    await code.getByLabel('Título do bloco de código').focus()
    assert.match(await saved(), /Linha criada em espaço vazio\./)

    const slash = async () => {
      await surface.evaluate(element => {
        const paragraph = document.createElement('p'); paragraph.innerHTML = '<br>'; element.append(paragraph)
        element.focus()
        const range = document.createRange(); range.selectNodeContents(paragraph); range.collapse(true)
        const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range)
      })
      await page.keyboard.type('/')
      await page.getByRole('listbox', { name: 'Comandos rápidos' }).waitFor()
    }
    await slash()
    const menu = page.getByRole('listbox', { name: 'Comandos rápidos' })
    assert.equal(await menu.getByRole('option').count(), 14)
    assert.equal(await menu.locator('.text-amber-400, .text-indigo-400, .text-blue-400, .text-emerald-400').count(), 0)
    assert.equal(await menu.getByText('Células editáveis, linhas e colunas').count(), 0)
    assert.equal(await menu.getByText('Área com formatação monospace').count(), 0)
    assert.ok((await menu.boundingBox()).width < 250)
    await page.screenshot({ path: path.join(dist, 'editor-blocks-preview.png'), fullPage: true })
    await menu.getByRole('option', { name: 'Callout de Dica', exact: true }).click()
    assert.equal(await page.locator('.editor-callout').count(), 1)
    await callout.getByLabel('Conteúdo do callout').focus()
    await page.keyboard.press('Backspace')
    assert.equal(await page.locator('.editor-callout').count(), 0, 'An empty callout can be removed with Backspace')
    await slash()
    await menu.getByRole('option', { name: 'Bloco de Código', exact: true }).click()
    assert.equal(await page.locator('.editor-code-block').count(), 2)
    await page.locator('.editor-code-block').last().getByLabel('Conteúdo do bloco de código').focus()
    await page.keyboard.press('Backspace')
    assert.equal(await page.locator('.editor-code-block').count(), 1)
    await page.getByTitle('Modo Leitura (Visualização pura)').click()
    assert.equal(await code.locator('textarea, input').count(), 0)
    assert.equal(await code.locator('pre code').innerText(), content)
    await page.getByTitle('Modo Edição ao Vivo (Live Preview no estilo Obsidian)').click()
    await code.getByRole('button', { name: 'Excluir bloco de código' }).click()
    assert.equal(await page.locator('.editor-code-block').count(), 0)
    await page.reload(); await openNote()
    assert.equal(await page.locator('.editor-callout, .editor-code-block').count(), 0)
    assert.match(await saved(), /Texto entre código e dica\./)
    assert.match(await saved(), /Linha criada em espaço vazio\./)
    assert.deepEqual(errors, [])
    console.log('Editor block checks passed: code editing/paste/header/copy, callout/code deletion, Markdown preservation, writable gaps, blank canvas and compact slash menu.')
  } catch (error) {
    await page?.screenshot({ path: path.join(dist, 'editor-blocks-failure.png'), fullPage: true })
    if (page) fs.writeFileSync(path.join(dist, 'editor-blocks-failure.html'), await page.content())
    throw error
  } finally { await browser?.close(); await new Promise(resolve => server.close(resolve)) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
