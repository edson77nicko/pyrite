// Run after npm run build. Optional arguments: Playwright package and Chromium executable.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const http = require('node:http')
const { chromium } = require(process.argv[2] || 'playwright')

async function main() {
  const dist = path.resolve(__dirname, '../dist')
  const server = http.createServer((request, response) => {
    const pathname = decodeURIComponent(new URL(request.url, 'http://localhost').pathname)
    const file = path.resolve(dist, '.' + (pathname === '/' ? '/index.html' : pathname))
    if (!file.startsWith(dist + path.sep) || !fs.existsSync(file)) { response.writeHead(404).end(); return }
    response.setHeader('Content-Type', ({ '.js': 'text/javascript', '.css': 'text/css', '.html': 'text/html', '.png': 'image/png' })[path.extname(file)] || 'application/octet-stream')
    response.end(fs.readFileSync(file))
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  let browser
  let page
  try {
    browser = await chromium.launch({ headless: true, executablePath: process.argv[3] })
    page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(() => {
      if (localStorage.getItem('table-test-seeded')) return
      const note = { id: 'table-test', title: 'Tabela de validação', content: '| Nome | Função | Local |\n| --- | --- | --- |\n| Olivia | Design | Vancouver |\n| Preston | Pesquisa | Nova Deli |', folder: 'Testes', tags: [], createdAt: Date.now(), updatedAt: Date.now() }
      localStorage.setItem('pyrite_vault_notes', JSON.stringify([note, { ...note, id: 'other-test', title: 'Outra nota de teste', content: 'Texto de outra nota.' }]))
      localStorage.setItem('pyrite_vault_folders', JSON.stringify(['Testes']))
      localStorage.setItem('table-test-seeded', '1')
    })
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await page.locator('[title="Tabela de validação"]').click()
    const table = page.locator('.pyrita-table')
    const cell = (row, column) => table.locator(`textarea[data-row="${row}"][data-column="${column}"]`)
    await cell(0, 0).fill('Olivia | Wilson')
    assert.equal(await cell(0, 0).inputValue(), 'Olivia | Wilson')
    await cell(-1, 0).fill('Pessoa')
    await table.getByRole('button', { name: 'Adicionar linha', exact: true }).click()
    assert.equal(await table.locator('tbody tr').count(), 3)
    await table.getByRole('button', { name: 'Adicionar coluna', exact: true }).click()
    assert.equal(await table.locator('thead textarea').count(), 4)
    await table.getByRole('button', { name: 'Opções da coluna 2', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Inserir coluna à esquerda' }).click()
    assert.equal(await table.locator('thead textarea').count(), 5)
    assert.equal(await cell(0, 2).inputValue(), 'Design')
    await cell(0, 1).fill('Primeira linha\nSegunda linha')
    await table.getByRole('button', { name: 'Opções da coluna 5', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Excluir coluna', exact: true }).click()
    assert.equal(await table.locator('thead textarea').count(), 4)
    await table.getByRole('button', { name: 'Opções da linha 2', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Duplicar linha' }).click()
    assert.equal(await table.locator('tbody tr').count(), 4)
    await table.getByRole('separator', { name: 'Redimensionar coluna 1', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('pyrite_vault_notes')).find(note => note.id === 'table-test').content)
    assert.match(await saved(), /"widths":\[196,/)
    await table.getByRole('button', { name: 'Opções da coluna 1', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Filtrar por esta coluna' }).click()
    await table.getByPlaceholder('Buscar nesta coluna…').fill('Olivia')
    assert.equal(await table.locator('tbody tr').count(), 1)
    assert.match(await saved(), /Preston/, 'Filtering must not remove saved rows')
    await table.getByTitle('Limpar filtro').click()
    await cell(3, 2).evaluate(element => {
      const clipboardData = new DataTransfer()
      clipboardData.setData('text/plain', 'A\tB\tC\nD\tE\tF')
      element.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
    })
    assert.equal(await table.locator('thead textarea').count(), 5)
    assert.equal(await cell(4, 4).inputValue(), 'F')
    await cell(4, 4).focus()
    await page.keyboard.press('Control+z')
    assert.equal(await table.locator('thead textarea').count(), 4)
    await cell(0, 0).focus()
    await page.keyboard.press('Control+y')
    assert.equal(await cell(4, 4).inputValue(), 'F')
    await page.locator('[title="Outra nota de teste"]').click()
    await page.locator('[title="Tabela de validação"]').click()
    assert.equal(await cell(0, 0).inputValue(), 'Olivia | Wilson')
    await page.reload()
    await page.locator('[title="Tabela de validação"]').click()
    assert.equal(await cell(4, 4).inputValue(), 'F')
    assert.equal(await cell(-1, 0).inputValue(), 'Pessoa')
    assert.equal(await cell(0, 1).inputValue(), 'Primeira linha\nSegunda linha')
    await page.getByTitle('Modo Leitura (Visualização pura)').click()
    assert.equal(await table.locator('textarea').count(), 0)
    assert.match(await table.innerText(), /Olivia \| Wilson/)
    await page.getByTitle('Modo Edição ao Vivo (Live Preview no estilo Obsidian)').click()
    await table.getByRole('button', { name: 'Opções da coluna 1', exact: true }).click()
    await page.screenshot({ path: path.join(dist, 'table-editor-preview.png'), fullPage: true })
    await page.keyboard.press('Escape')
    await page.locator('[contenteditable="true"]').last().evaluate(element => {
      element.focus()
      const paragraph = document.createElement('p')
      paragraph.textContent = '/'
      element.append(paragraph)
      const range = document.createRange(); range.setStart(paragraph.firstChild, 1); range.collapse(true)
      const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range)
      element.dispatchEvent(new InputEvent('input', { bubbles: true, inputType: 'insertText', data: '/' }))
    })
    await page.getByText('Comandos Rápidos', { exact: true }).waitFor()
    assert.equal(await page.getByText('Cartão KPI (Métrica Concêntrica)', { exact: true }).count(), 0)
    assert.equal(await page.getByText('Linha do Tempo / Roadmap', { exact: true }).count(), 0)
    assert.equal(await page.getByText('Comparativo Lado a Lado', { exact: true }).count(), 0)
    assert.equal(await page.getByText('Cartão Embutido (Nested Card)', { exact: true }).count(), 0)
    await page.getByText('Células editáveis, linhas e colunas', { exact: true }).click()
    assert.equal(await page.locator('.pyrita-table').count(), 2, 'Slash insertion creates an editable table')
    await page.getByTitle('Inserir tabela').click()
    assert.equal(await page.locator('.pyrita-table').count(), 3, 'Toolbar insertion creates an editable table')
    fs.writeFileSync(path.join(dist, 'table-editor-saved.md'), await saved())
    await page.reload()
    await page.locator('[title="Tabela de validação"]').click()
    assert.equal(await page.locator('.pyrita-table').count(), 3, 'New tables must survive a reload')
    assert.deepEqual(errors, [], 'No browser runtime errors')
    console.log('Editor table browser checks passed (editing, rows, columns, paste, resizing, filter, undo, reload, reading and slash commands).')
  } catch (error) {
    await page?.screenshot({ path: path.join(dist, 'table-editor-failure.png'), fullPage: true })
    if (page) fs.writeFileSync(path.join(dist, 'table-editor-failure.html'), await page.locator('[contenteditable="true"]').last().innerHTML())
    throw error
  } finally { await browser?.close(); await new Promise(resolve => server.close(resolve)) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
